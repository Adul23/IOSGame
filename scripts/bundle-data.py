"""Generate file:// fallback. Edit JSON sources, then run this script."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
data = {kind: {lang: json.loads((root / kind / f'{lang}.json').read_text()) for lang in ('ru', 'en')} for kind in ('questions', 'i18n')}
(root / 'js/bundled-data.js').write_text('// Generated by scripts/bundle-data.py. Do not edit.\nwindow.ParkourData = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
